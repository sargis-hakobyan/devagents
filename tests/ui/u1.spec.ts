test('sign-out ends the session and the API refuses unauthenticated or cross-origin browser access', async ({ page, request }) => {
  await signIn(page);
  expect((await request.get(`${base}/tasks`)).status()).toBe(401);
  const cookies = await page.context().cookies(); const session = cookies.find(c => c.name === 'devagents_session')!;
  expect(session.httpOnly).toBe(true); expect(session.sameSite).toBe('Strict');
  const foreign = await request.get(`${base}/tasks`, { headers: { cookie: `devagents_session=${session.value}`, origin: 'http://localhost:9999' } });
  expect(foreign.status()).toBe(403);
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page).toHaveURL(`${base}/ui/signed-out`);
  await expect(page.getByText('devagents ui', { exact: true })).toBeVisible();
  await page.goto(`${base}/ui/tasks`);
  await expect(page).toHaveURL(`${base}/ui/signed-out`);
});
