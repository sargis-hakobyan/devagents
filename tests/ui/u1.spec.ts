test('disconnection shows a banner with the last update and reconnecting appends history without duplicates', async ({ page }) => {
  await signIn(page); const t = await find('[multi]');
  await page.goto(`${base}/ui/tasks/${t.id}`);
  await page.getByRole('tab', { name: /Activity/ }).click();
  const countBefore = await page.locator('ol.timeline li').count();
  const label = await page.getByRole('tab', { name: /Activity/ }).textContent();
  await page.route('**/*', route => route.request().url().startsWith(base) && !route.request().url().includes('/ui/assets/') ? route.abort('connectionrefused') : route.continue());
  await expect(page.getByRole('status')).toContainText('Service disconnected', { timeout: 15000 });
  await expect(page.getByRole('status')).toContainText('last update');
  await expect(page.getByRole('status')).toContainText('nothing is invented');
  await page.screenshot({ path: join(shots, 'u1-disconnected.png') });
  await page.unroute('**/*');
  await page.getByRole('button', { name: 'Retry now' }).click();
  await expect(page.getByRole('status')).toHaveCount(0, { timeout: 15000 });
  await expect(page.getByRole('tab', { name: /Activity/ })).toHaveText(label!);
  expect(await page.locator('ol.timeline li').count()).toBe(countBefore);
  await page.reload();
  await page.getByRole('tab', { name: /Activity/ }).click();
  await expect(page.getByRole('tab', { name: /Activity/ })).toHaveText(label!);
});
