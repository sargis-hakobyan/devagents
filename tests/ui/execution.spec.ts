import { test, expect } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import type { AddressInfo } from 'node:net';
import { fixture } from '../helpers.js';
import { createApi } from '../../src/api/server.js';
import { fixtureDir, port } from './playwright.config.js';

test('execution updates live from reviewer findings to developer repair and re-review, preserving order after reload', async ({ page }) => {
  const f = await fixture();
  const fixtureToken = (await readFile(join(fixtureDir, 'api-token'), 'utf8')).trim();
  const status = await (await fetch(`http://127.0.0.1:${port}/status`, { headers: { authorization: `Bearer ${fixtureToken}` } })).json();
  const server = createApi(f.service, 'synthetic-execution-token', { uiRoot: join(process.cwd(), 'dist/ui'), status: async () => status });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  try {
    const task = f.service.submit({ projectId: 'fixture', request: 'Live repair timeline fixture', mode: 'autonomous' }, 'execution-browser');
    const record = (kind: string, data: object) => f.store.record(task.id, kind, data);
    const start = (runId: string, phase: string, agentId: string, workItemId = 'backend') => record('run-started', { runId, phase, agentId, workItemId });
    const end = (runId: string, output: object) => record('run-completed', { runId, output });
    start('developer', 'implementation', 'Backend Developer');
    start('frontend', 'implementation', 'Frontend Developer', 'frontend');
    end('frontend', { summary: 'Updated menu font' }); end('developer', { summary: 'Added login timestamp' });
    for (let i = 0; i < 220; i++) record('progress', { runId: 'developer', kind: 'output', data: { text: 'padding' } });
    const checks = (failed = false) => { for (let i = 0; i < 5; i++) record('validation', { workItemId: 'backend', executable: 'node', args: ['--test', `check-${i}.test.js`], exitCode: failed && i === 4 ? 1 : 0 }); };
    checks();
    start('review', 'review', 'Code Reviewer');
    const bootstrap = await fetch(`${origin}/ui/bootstrap`, { method: 'POST', headers: { authorization: 'Bearer synthetic-execution-token', 'content-type': 'application/json' }, body: '{}' });
    await page.goto((await bootstrap.json()).url); await page.goto(`${origin}/ui/tasks/${task.id}`);
    const timeline = page.getByRole('region', { name: 'Execution workflow' });
    await expect(timeline.locator('[data-execution-id="run-review"]')).toContainText('Working now');
    const groups = timeline.locator('[data-validation-group]');
    await expect(groups).toHaveCount(1);
    await expect(groups.first().locator('summary')).toHaveText('5 automated checks5 passed');
    await expect(groups.first().locator('[data-validation-id]').first()).not.toBeVisible();
    await groups.first().locator('summary').click();
    await expect(groups.first().locator('[data-validation-id]')).toHaveCount(5);
    await expect(groups.first().getByText('backend · node --test check-4.test.js', { exact: true })).toBeVisible();
    await groups.first().locator('summary').click();
    await expect(timeline.locator('.workflow-number')).toHaveText(['1', '2', '3']);
    await expect(timeline.getByRole('heading', { name: 'DevAgents', exact: true })).toHaveCount(0);
    await expect(timeline.locator('[data-execution-id="run-developer"]')).toContainText('parallel work');
    end('review', { approved: false, summary: 'SSO login is not persisted', findings: ['Persist the successful SSO login timestamp.', '<img src=x onerror=alert(1)>'] });
    start('repair', 'implementation', 'Backend Developer');
    const repair = timeline.locator('[data-execution-id="run-repair"]');
    await expect(repair).toContainText('Working now', { timeout: 10000 });
    await expect(repair).toContainText('Repair · backend · Attempt 2');
    await expect(repair).toContainText('Persist the successful SSO login timestamp.');
    await expect(timeline.locator('[data-execution-id="run-review"]')).toContainText('Changes requested');
    await expect(timeline.locator('article h3')).toHaveText(['Backend Developer', 'Frontend Developer', 'Code Reviewer', 'Backend Developer']);
    expect(await page.locator('img[src="x"]').count()).toBe(0);
    end('repair', { summary: 'SSO timestamp persisted; ready for verification' });
    checks(true);
    start('test-repair', 'implementation', 'Backend Developer');
    const testRepair = timeline.locator('[data-execution-id="run-test-repair"]');
    await expect(testRepair).toContainText('Working now', { timeout: 10000 });
    await expect(groups).toHaveCount(2);
    await expect(groups.nth(1).locator('summary')).toHaveText('5 automated checks4 passed · 1 failed');
    const feedback = testRepair.getByRole('link', { name: 'From automated checks' });
    await expect(feedback).toHaveAttribute('href', `#${await groups.nth(1).getAttribute('id')}`);
    end('test-repair', { summary: 'Fixed the failing test' });
    checks();
    start('review2', 'review', 'Code Reviewer'); end('review2', { approved: true, findings: [], summary: 'Verified the SSO fix' });
    await expect(timeline.locator('[data-execution-id="run-review2"]')).toContainText('Verified the SSO fix', { timeout: 10000 });
    await expect(timeline.locator('[data-execution-id="run-review2"]')).toContainText('Approved');
    record('commit-created', { commit: 'a'.repeat(40) });
    await page.reload(); await expect(timeline.locator('article h3')).toHaveText(['Backend Developer', 'Frontend Developer', 'Code Reviewer', 'Backend Developer', 'Backend Developer', 'Code Reviewer']);
    await expect(groups).toHaveCount(3);
    await expect(timeline.locator('.workflow-number')).toHaveText(['1', '2', '3', '4', '5', '6']);
    await expect(timeline.locator('.execution-commit')).toContainText('Created local commit');
    await expect(timeline.getByRole('heading', { name: 'DevAgents', exact: true })).toHaveCount(0);
    await expect(repair).toContainText('Check the later validation and review steps');
    const shots = join(process.cwd(), 'test-results/ui-screenshots'); await mkdir(shots, { recursive: true });
    await timeline.screenshot({ path: join(shots, 'execution-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(timeline).toBeVisible(); expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await timeline.screenshot({ path: join(shots, 'execution-mobile.png') });
    await page.route(`${origin}/tasks/${task.id}/execution`, route => route.fulfill({ status: 500, json: { error: 'fixture', message: 'Temporary outage' } }));
    await expect(timeline.getByRole('button', { name: 'Retry execution updates' })).toBeVisible({ timeout: 10000 });
    await expect(timeline.locator('article')).toHaveCount(6);
    await page.unroute(`${origin}/tasks/${task.id}/execution`); await timeline.getByRole('button', { name: 'Retry execution updates' }).click();
    await expect(timeline.getByRole('button', { name: 'Retry execution updates' })).not.toBeVisible();
  } finally { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); await f.cleanup(); }
});
